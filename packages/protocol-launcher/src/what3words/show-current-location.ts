/**
 * Show the user's current location in the what3words app.
 *
 * @returns what3words current-location URL.
 * @example
 * showCurrentLocation()
 * // => 'w3w://show?currentlocation'
 * @link https://developer.what3words.com/tutorial/mobile-linking-to-the-what3words-app
 */
export function showCurrentLocation() {
  return 'w3w://show?currentlocation'
}
