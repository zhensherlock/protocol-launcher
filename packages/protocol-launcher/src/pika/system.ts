/**
 * Open system foreground color picker in Pika.
 *
 * @returns Pika system foreground color picker URL.
 * @example
 * systemForeground()
 * // => 'pika://system/foreground'
 * @link https://github.com/superhighfives/pika/blob/main/Pika/Views/HelpView.swift
 */
export function systemForeground() {
  return 'pika://system/foreground'
}

/**
 * Open system background color picker in Pika.
 *
 * @returns Pika system background color picker URL.
 * @example
 * systemBackground()
 * // => 'pika://system/background'
 * @link https://github.com/superhighfives/pika/blob/main/Pika/Views/HelpView.swift
 */
export function systemBackground() {
  return 'pika://system/background'
}
