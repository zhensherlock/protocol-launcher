/**
 * Force light appearance in Pika.
 *
 * @returns Pika light appearance URL.
 * @example
 * light()
 * // => 'pika://appearance/light'
 * @link https://github.com/superhighfives/pika/blob/main/Pika/Views/HelpView.swift
 */
export function light() {
  return 'pika://appearance/light'
}

/**
 * Force dark appearance in Pika.
 *
 * @returns Pika dark appearance URL.
 * @example
 * dark()
 * // => 'pika://appearance/dark'
 * @link https://github.com/superhighfives/pika/blob/main/Pika/Views/HelpView.swift
 */
export function dark() {
  return 'pika://appearance/dark'
}

