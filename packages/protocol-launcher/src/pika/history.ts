/**
 * Show the history drawer in Pika.
 *
 * @returns Pika show history URL.
 * @example
 * showHistory()
 * // => 'pika://history/show'
 * @link https://github.com/superhighfives/pika/blob/main/Pika/Views/HelpView.swift
 */
export function showHistory() {
  return 'pika://history/show'
}

/**
 * Hide the history drawer in Pika.
 *
 * @returns Pika hide history URL.
 * @example
 * hideHistory()
 * // => 'pika://history/hide'
 * @link https://github.com/superhighfives/pika/blob/main/Pika/Views/HelpView.swift
 */
export function hideHistory() {
  return 'pika://history/hide'
}

/**
 * Toggle the history drawer in Pika.
 *
 * @returns Pika toggle history URL.
 * @example
 * toggleHistory()
 * // => 'pika://history/toggle'
 * @link https://github.com/superhighfives/pika/blob/main/Pika/Views/HelpView.swift
 */
export function toggleHistory() {
  return 'pika://history/toggle'
}
