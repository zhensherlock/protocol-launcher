/**
 * Put a selected Dropbox file's direct link on the clipboard.
 *
 * @returns Launch Center Pro Dropbox direct-link URL.
 * @example
 * dropboxCopyDirectLink()
 * // => 'launch://dropbox/copy/directlink'
 * @link https://help.contrast.co/hc/en-us/articles/203351237-2-3-Release-Notes
 */
export function dropboxCopyDirectLink() {
  return 'launch://dropbox/copy/directlink'
}
