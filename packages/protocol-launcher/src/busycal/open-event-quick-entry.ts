/**
 * Open BusyCal's Quick Entry field for a new event on macOS.
 *
 * @returns BusyCal macOS new event Quick Entry URL.
 * @example
 * openEventQuickEntry()
 * // => 'busycal://newEvent'
 * @link https://www.busymac.com/docs/busycal/70621-url-handler/
 */
export function openEventQuickEntry() {
  return 'busycal://newEvent'
}
