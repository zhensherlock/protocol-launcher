/**
 * Open BusyCal's Quick Entry field for a new task on macOS.
 *
 * @returns BusyCal macOS new task Quick Entry URL.
 * @example
 * openTaskQuickEntry()
 * // => 'busycal://newTask'
 * @link https://www.busymac.com/docs/busycal/70621-url-handler/
 */
export function openTaskQuickEntry() {
  return 'busycal://newTask'
}
