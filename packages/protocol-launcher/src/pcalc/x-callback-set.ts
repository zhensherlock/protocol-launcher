/**
 * Return PCalc's x-callback-url endpoint for setting the display from a callback result.
 *
 * @returns PCalc x-callback set URL.
 * @example
 * xCallbackSet()
 * // => 'pcalc://x-callback-url/set'
 *
 * @link https://www.pcalc.com/ios/history.html
 */
export function xCallbackSet() {
  return 'pcalc://x-callback-url/set'
}
